IF DB_ID(N'sgred') IS NULL
BEGIN
  CREATE DATABASE sgred;
END;
GO
USE sgred;
GO
IF OBJECT_ID('dbo.Roles','U') IS NULL
CREATE TABLE dbo.Roles (Id INT IDENTITY PRIMARY KEY, Nombre NVARCHAR(30) NOT NULL UNIQUE);

IF OBJECT_ID('dbo.Usuarios','U') IS NULL
CREATE TABLE dbo.Usuarios (
  Id INT IDENTITY PRIMARY KEY, RolId INT NOT NULL FOREIGN KEY REFERENCES dbo.Roles(Id),
  Documento NVARCHAR(30) NOT NULL UNIQUE, Nombres NVARCHAR(100) NOT NULL, Apellidos NVARCHAR(100) NOT NULL,
  Correo NVARCHAR(150) NOT NULL UNIQUE, PasswordHash NVARCHAR(255) NULL, Telefono NVARCHAR(15) NULL,
  EntidadRepresentada NVARCHAR(150) NULL, PuedeGestionarUsuarios BIT NOT NULL DEFAULT 0,
  Activo BIT NOT NULL DEFAULT 1, IntentosFallidos INT NOT NULL DEFAULT 0,
  BloqueadoHasta DATETIME2 NULL, FechaCreacion DATETIME2 NOT NULL DEFAULT SYSUTCDATETIME(),
  FechaActualizacion DATETIME2 NOT NULL DEFAULT SYSUTCDATETIME()
);

IF OBJECT_ID('dbo.Sesiones','U') IS NULL
CREATE TABLE dbo.Sesiones (
  Id UNIQUEIDENTIFIER PRIMARY KEY DEFAULT NEWID(), UsuarioId INT NOT NULL FOREIGN KEY REFERENCES dbo.Usuarios(Id),
  FechaCreacion DATETIME2 NOT NULL DEFAULT SYSUTCDATETIME(), UltimaActividad DATETIME2 NOT NULL DEFAULT SYSUTCDATETIME(),
  Revocada BIT NOT NULL DEFAULT 0, FechaRevocacion DATETIME2 NULL
);

IF OBJECT_ID('dbo.Zonas','U') IS NULL
CREATE TABLE dbo.Zonas (Id INT IDENTITY PRIMARY KEY, Nombre NVARCHAR(100) NOT NULL UNIQUE);
IF OBJECT_ID('dbo.TiposUnidad','U') IS NULL
CREATE TABLE dbo.TiposUnidad (Id INT IDENTITY PRIMARY KEY, Nombre NVARCHAR(100) NOT NULL UNIQUE);
IF OBJECT_ID('dbo.TiposEscenario','U') IS NULL
CREATE TABLE dbo.TiposEscenario (Id INT IDENTITY PRIMARY KEY, Nombre NVARCHAR(100) NOT NULL UNIQUE);
IF OBJECT_ID('dbo.Disciplinas','U') IS NULL
CREATE TABLE dbo.Disciplinas (Id INT IDENTITY PRIMARY KEY, Nombre NVARCHAR(100) NOT NULL UNIQUE);
IF OBJECT_ID('dbo.TiposUso','U') IS NULL
CREATE TABLE dbo.TiposUso (Id INT IDENTITY PRIMARY KEY, Nombre NVARCHAR(100) NOT NULL UNIQUE);

IF OBJECT_ID('dbo.UnidadesDeportivas','U') IS NULL
CREATE TABLE dbo.UnidadesDeportivas (
  Id INT IDENTITY PRIMARY KEY, Nombre NVARCHAR(150) NOT NULL UNIQUE, ZonaId INT NOT NULL FOREIGN KEY REFERENCES dbo.Zonas(Id),
  TipoUnidadId INT NOT NULL FOREIGN KEY REFERENCES dbo.TiposUnidad(Id), Direccion NVARCHAR(200) NOT NULL,
  Activa BIT NOT NULL DEFAULT 1
);

IF OBJECT_ID('dbo.UnidadDisciplina','U') IS NULL
CREATE TABLE dbo.UnidadDisciplina (
  UnidadId INT NOT NULL FOREIGN KEY REFERENCES dbo.UnidadesDeportivas(Id),
  DisciplinaId INT NOT NULL FOREIGN KEY REFERENCES dbo.Disciplinas(Id),
  PRIMARY KEY (UnidadId, DisciplinaId)
);

IF OBJECT_ID('dbo.AdministrativoUnidad','U') IS NULL
CREATE TABLE dbo.AdministrativoUnidad (
  UsuarioId INT NOT NULL FOREIGN KEY REFERENCES dbo.Usuarios(Id),
  UnidadId INT NOT NULL FOREIGN KEY REFERENCES dbo.UnidadesDeportivas(Id),
  PRIMARY KEY (UsuarioId, UnidadId)
);
